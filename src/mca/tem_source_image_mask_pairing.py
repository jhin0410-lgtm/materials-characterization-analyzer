def inspect_hdf5_pair(
    image_path: str | Path,
    mask_path: str | Path,
    *,
    config: SourceImageMaskPairingConfig,
    pair: PairSpec,
    image_member_sha256: str,
    mask_member_sha256: str,
) -> dict[str, Any]:
    image_path = Path(image_path)
    mask_path = Path(mask_path)
    frame_rows: list[dict[str, Any]] = []
    with h5py.File(image_path, "r") as image_h5, h5py.File(mask_path, "r") as mask_h5:
        _validate_hdf5_root(
            image_h5,
            member=pair.image_member,
            dataset_name=config.image_dataset_name,
            expected_shape=config.expected_shape,
            expected_dtype=config.image_dtype,
        )
        _validate_hdf5_root(
            mask_h5,
            member=pair.mask_member,
            dataset_name=config.mask_dataset_name,
            expected_shape=config.expected_shape,
            expected_dtype=config.mask_dtype,
        )
        image_dataset = image_h5[config.image_dataset_name]
        mask_dataset = mask_h5[config.mask_dataset_name]
        same_shape = tuple(image_dataset.shape) == tuple(mask_dataset.shape)
        same_frame_count = image_dataset.shape[0] == mask_dataset.shape[0]
        if not same_shape or not same_frame_count:
            raise ValueError(f"HDF5 pair shape mismatch for {pair.pair_id}.")
        for frame_index in range(image_dataset.shape[0]):
            image_fp = _frame_fingerprint(image_dataset, frame_index, require_binary=False)
            mask_fp = _frame_fingerprint(mask_dataset, frame_index, require_binary=True)
            if abs(float(image_fp["mean"])) > config.image_mean_abs_tolerance:
                raise ValueError(
                    f"source image frame mean drift for {pair.pair_id} frame {frame_index}: "
                    f"{image_fp['mean']}"
                )
            if abs(float(image_fp["std"]) - 1.0) > config.image_std_abs_tolerance:
                raise ValueError(
                    f"source image frame standard deviation drift for "
                    f"{pair.pair_id} frame {frame_index}: {image_fp['std']}"
                )
            frame_rows.append(
                {
                    "pair_id": pair.pair_id,
                    "frame_index": int(frame_index),
                    "image_member": pair.image_member,
                    "mask_member": pair.mask_member,
                    "image_frame_sha256": image_fp["sha256"],
                    "mask_frame_sha256": mask_fp["sha256"],
                    "height_px": int(image_dataset.shape[1]),
                    "width_px": int(image_dataset.shape[2]),
                    "image_min": image_fp["minimum"],
                    "image_max": image_fp["maximum"],
                    "image_mean": image_fp["mean"],
                    "image_std": image_fp["std"],
                    "mask_foreground_fraction": mask_fp["mean"],
                    "pairing_basis": (
                        "source_description_exact_prefix_equal_shape_same_frame_index"
                    ),
                    "pairing_status": PAIRING_STATUS,
                    "independent_pairing_verification": False,
                    "pixel_calibration_applied": False,
                }
            )
        file_row = {
            "pair_id": pair.pair_id,
            "image_member": pair.image_member,
            "mask_member": pair.mask_member,
            "image_member_sha256": image_member_sha256,
            "mask_member_sha256": mask_member_sha256,
            "image_dataset_name": config.image_dataset_name,
            "mask_dataset_name": config.mask_dataset_name,
            "shape": json.dumps(list(image_dataset.shape)),
            "image_dtype": str(image_dataset.dtype),
            "mask_dtype": str(mask_dataset.dtype),
            "frame_count": int(image_dataset.shape[0]),
            "same_shape": same_shape,
            "same_frame_count": same_frame_count,
            "attributes_present": False,
            "all_frames_numerically_standardized": True,
            "pairing_status": PAIRING_STATUS,
            "source_asserted_correspondence": True,
            "independent_pairing_verification": False,
            "pixel_calibration_available": False,
        }
    return {"file_row": file_row, "frame_rows": frame_rows}


def _validate_hdf5_root(
    handle: h5py.File,
    *,
    member: str,
    dataset_name: str,
    expected_shape: tuple[int, int, int],
    expected_dtype: str,
) -> None:
    if list(handle.keys()) != [dataset_name]:
        raise ValueError(
            f"{member} must contain only dataset {dataset_name!r}; "
            f"found {list(handle.keys())!r}."
        )
    if len(handle.attrs) != 0:
        raise ValueError(f"{member} root attributes changed from the pinned contract.")
    dataset = handle[dataset_name]
    if not isinstance(dataset, h5py.Dataset):
        raise ValueError(f"{member} {dataset_name!r} is not an HDF5 dataset.")
    if tuple(dataset.shape) != expected_shape:
        raise ValueError(
            f"{member} shape {tuple(dataset.shape)} != {expected_shape}."
        )
    if str(dataset.dtype) != expected_dtype:
        raise ValueError(f"{member} dtype {dataset.dtype} != {expected_dtype}.")
    if len(dataset.attrs) != 0:
        raise ValueError(f"{member} dataset attributes changed from the pinned contract.")


def _frame_fingerprint(
    dataset: h5py.Dataset,
    frame_index: int,
    *,
    require_binary: bool,
) -> dict[str, float | str]:
    digest = hashlib.sha256()
    minimum = math.inf
    maximum = -math.inf
    total = 0.0
    total_sq = 0.0
    count = 0
    height = int(dataset.shape[1])
    for start in range(0, height, 256):
        block = np.asarray(dataset[frame_index, start : start + 256, :])
        if not np.isfinite(block).all():
            raise ValueError(f"non-finite value in frame {frame_index}.")
        if require_binary:
            valid = np.logical_or(block == 0.0, block == 1.0)
            if not bool(valid.all()):
                bad = np.unique(block[~valid])[:10].tolist()
                raise ValueError(
                    f"non-binary mask value in frame {frame_index}: {bad}"
                )
        digest.update(np.ascontiguousarray(block).tobytes(order="C"))
        minimum = min(minimum, float(np.min(block)))
        maximum = max(maximum, float(np.max(block)))
        total += float(np.sum(block, dtype=np.float64))
        total_sq += float(
            np.sum(np.square(block, dtype=np.float64), dtype=np.float64)
        )
        count += int(block.size)
    mean = total / count
    variance = max(0.0, total_sq / count - mean * mean)
    return {
        "sha256": digest.hexdigest(),
        "minimum": minimum,
        "maximum": maximum,
        "mean": mean,
        "std": math.sqrt(variance),
    }


def _archive_spec(payload: Mapping[str, Any], context: str) -> ArchiveSpec:
    _reject_unknown(
        payload,
        {"name", "url", "md5", "sha256", "expected_members"},
        context,
    )
    return ArchiveSpec(
        name=_required_text(payload, "name"),
        url=_required_text(payload, "url"),
        md5=_digest(payload, "md5", 32),
        sha256=_digest(payload, "sha256", 64),
        expected_members=tuple(_text_list(payload, "expected_members")),
    )


def _validate_public_archive(
    archive: ArchiveSpec,
    *,
    expected_name: str,
    expected_md5: str,
    expected_sha256: str,
    expected_members: tuple[str, ...],
    expected_url: str,
) -> None:
    expected = {
        "name": expected_name,
        "url": expected_url,
        "md5": expected_md5,
        "sha256": expected_sha256,
        "expected_members": expected_members,
    }
    for field, value in expected.items():
        actual = getattr(archive, field)
        if actual != value:
            raise ValueError(
                f"public archive mismatch for {field}: {actual!r} != {value!r}"
            )


def _acquire_archive(
    spec: ArchiveSpec,
    supplied_path: str | Path | None,
    temporary: Path,
) -> tuple[Path, str]:
    destination = temporary / spec.name
    if supplied_path is None:
        _download(spec.url, destination)
        return destination, "downloaded_from_pinned_public_url"
    supplied = Path(supplied_path)
    if not supplied.is_file():
        raise FileNotFoundError(f"archive does not exist: {supplied}")
    if supplied.is_symlink():
        raise ValueError(f"archive path must not be a symlink: {supplied}")
    return supplied, "user_supplied_local_copy_verified_against_pinned_hashes"


def _verify_archive(path: Path, spec: ArchiveSpec) -> dict[str, str]:
    md5 = _hash_file(path, "md5")
    sha256 = _hash_file(path, "sha256")
    if md5 != spec.md5:
        raise ValueError(f"{spec.name} MD5 mismatch: {md5} != {spec.md5}")
    if sha256 != spec.sha256:
        raise ValueError(
            f"{spec.name} SHA-256 mismatch: {sha256} != {spec.sha256}"
        )
    return {"md5": md5, "sha256": sha256}


def _validate_zip_contract(
    archive: Path, expected_members: tuple[str, ...]
) -> dict[str, Any]:
    expected = set(expected_members)
    observed: set[str] = set()
    metadata: list[str] = []
    with zipfile.ZipFile(archive) as zf:
        for info in zf.infolist():
            _validate_zip_info(info)
            name = info.filename
            path = PurePosixPath(name)
            if name.startswith("__MACOSX/") or path.name.startswith("._"):
                metadata.append(name)
            elif not info.is_dir():
                observed.add(name)
        if observed != expected:
            raise ValueError(
                "archive members do not match pinned contract; "
                f"missing={sorted(expected-observed)}, "
                f"unexpected={sorted(observed-expected)}"
            )
    return {
        "data_members": sorted(observed),
        "metadata_members": sorted(metadata),
        "data_member_count": len(observed),
        "metadata_member_count": len(metadata),
        "safe_paths_verified": True,
        "symlinks_absent": True,
        "encrypted_entries_absent": True,
    }


def _validate_zip_info(info: zipfile.ZipInfo) -> None:
    name = info.filename
    normalized = name.replace("\\", "/")
    path = PurePosixPath(normalized)
    if name != normalized or path.is_absolute() or ".." in path.parts:
        raise ValueError(f"unsafe archive path: {name!r}")
    if any(part in ("", ".") for part in path.parts):
        raise ValueError(f"non-canonical archive path: {name!r}")
    mode = (info.external_attr >> 16) & 0xFFFF
    if stat.S_ISLNK(mode):
        raise ValueError(f"archive symlink rejected: {name!r}")
    if info.flag_bits & 0x1:
        raise ValueError(f"encrypted archive entry rejected: {name!r}")


def _extract_member(
    archive: zipfile.ZipFile, member: str, destination: Path
) -> str:
    digest = hashlib.sha256()
    with archive.open(member) as source, destination.open("wb") as target:
        while chunk := source.read(1024 * 1024):
            digest.update(chunk)
            target.write(chunk)
    return digest.hexdigest()


def _download(url: str, destination: Path) -> None:
    request = urllib.request.Request(
        url, headers={"User-Agent": "materials-characterization-analyzer"}
    )
    with urllib.request.urlopen(request, timeout=180) as response, destination.open(
        "wb"
    ) as output:
        shutil.copyfileobj(response, output, length=1024 * 1024)


def _hash_file(path: Path, algorithm: str) -> str:
    digest = hashlib.new(algorithm)
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _prepare_empty_output(path: str | Path) -> Path:
    output = Path(path)
    if output.exists():
        if not output.is_dir():
            raise ValueError(f"output path is not a directory: {output}")
        if any(output.iterdir()):
            raise FileExistsError(
                f"output directory must be absent or empty: {output}"
            )
    else:
        output.mkdir(parents=True)
    return output


