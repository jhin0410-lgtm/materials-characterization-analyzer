def _build_artifact_manifest(
    output: Path,
    files: Iterable[Path],
    *,
    case_id: str,
    image_archive_sha256: str,
    mask_archive_sha256: str,
) -> dict[str, Any]:
    records = []
    for path in sorted(files, key=lambda item: item.name):
        records.append(
            {
                "path": path.relative_to(output).as_posix(),
                "bytes": path.stat().st_size,
                "sha256": _hash_file(path, "sha256"),
            }
        )
    return {
        "schema_version": "1.0",
        "case_id": case_id,
        "image_archive_sha256": image_archive_sha256,
        "mask_archive_sha256": mask_archive_sha256,
        "artifact_count": len(records),
        "artifacts": records,
    }


def _write_csv(
    path: Path,
    rows: Iterable[Mapping[str, Any]],
    columns: tuple[str, ...],
) -> None:
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(
            handle, fieldnames=list(columns), extrasaction="raise"
        )
        writer.writeheader()
        for row in rows:
            writer.writerow({column: row.get(column) for column in columns})


def _write_json(path: Path, payload: Mapping[str, Any]) -> None:
    path.write_text(
        json.dumps(payload, indent=2, sort_keys=True, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )


def _mapping(payload: Mapping[str, Any], field: str) -> Mapping[str, Any]:
    value = payload.get(field)
    if not isinstance(value, Mapping):
        raise ValueError(f"{field} must be an object.")
    return value


def _required_text(payload: Mapping[str, Any], field: str) -> str:
    value = payload.get(field)
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"{field} must be a non-empty string.")
    return value.strip()


def _text_list(payload: Mapping[str, Any], field: str) -> list[str]:
    value = payload.get(field)
    if not isinstance(value, list) or not value:
        raise ValueError(f"{field} must be a non-empty list.")
    result: list[str] = []
    for item in value:
        if not isinstance(item, str) or not item.strip():
            raise ValueError(f"{field} entries must be non-empty strings.")
        _validate_member_name(item.strip())
        result.append(item.strip())
    return result


def _digest(payload: Mapping[str, Any], field: str, length: int) -> str:
    value = _required_text(payload, field).lower()
    if len(value) != length or any(
        character not in "0123456789abcdef" for character in value
    ):
        raise ValueError(
            f"{field} must be a {length}-character hexadecimal digest."
        )
    return value


def _validate_member_name(member: str) -> None:
    normalized = member.replace("\\", "/")
    path = PurePosixPath(normalized)
    if (
        member != normalized
        or path.is_absolute()
        or ".." in path.parts
        or len(path.parts) != 1
    ):
        raise ValueError(
            f"expected member must be a safe root-level filename: {member!r}"
        )


def _reject_unknown(
    payload: Mapping[str, Any], allowed: set[str], context: str
) -> None:
    unknown = sorted(set(payload) - allowed)
    if unknown:
        raise ValueError(f"unknown {context} field(s): {', '.join(unknown)}")


