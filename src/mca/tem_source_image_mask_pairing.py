@dataclass(frozen=True)
class ArchiveSpec:
    """One exact externally hosted ZIP archive."""

    name: str
    url: str
    md5: str
    sha256: str
    expected_members: tuple[str, ...]


@dataclass(frozen=True)
class PairSpec:
    """One explicit source-image-member to mask-member identity mapping."""

    pair_id: str
    image_member: str
    mask_member: str


@dataclass(frozen=True)
class SourceImageMaskPairingConfig:
    """Strict contract for the public source-image and mask pairing audit."""

    case_id: str
    record_id: int
    doi: str
    dataset_version: str
    license: str
    source_description: str
    paper_doi: str
    paper_reported_four_k_pixel_size_pm: float
    calibration_binding_status: str
    image_archive: ArchiveSpec
    mask_archive: ArchiveSpec
    pairs: tuple[PairSpec, ...]
    image_dataset_name: str
    mask_dataset_name: str
    expected_shape: tuple[int, int, int]
    image_dtype: str
    mask_dtype: str
    image_mean_abs_tolerance: float
    image_std_abs_tolerance: float
    attributes_expected: bool

    @classmethod
    def from_mapping(cls, payload: Mapping[str, Any]) -> "SourceImageMaskPairingConfig":
        _reject_unknown(
            payload,
            {
                "case_id",
                "source",
                "literature_context",
                "image_archive",
                "mask_archive",
                "pairs",
                "hdf5_contract",
            },
            "config",
        )
        source = _mapping(payload, "source")
        literature = _mapping(payload, "literature_context")
        image_archive = _archive_spec(_mapping(payload, "image_archive"), "image_archive")
        mask_archive = _archive_spec(_mapping(payload, "mask_archive"), "mask_archive")
        contract = _mapping(payload, "hdf5_contract")
        _reject_unknown(
            source,
            {"record_id", "doi", "dataset_version", "license", "source_description"},
            "source",
        )
        _reject_unknown(
            literature,
            {
                "paper_doi",
                "paper_reported_four_k_pixel_size_pm",
                "calibration_binding_status",
            },
            "literature_context",
        )
        _reject_unknown(
            contract,
            {
                "image_dataset_name",
                "mask_dataset_name",
                "expected_shape",
                "image_dtype",
                "mask_dtype",
                "image_mean_abs_tolerance",
                "image_std_abs_tolerance",
                "attributes_expected",
            },
            "hdf5_contract",
        )
        pair_entries = payload.get("pairs")
        if not isinstance(pair_entries, list) or not pair_entries:
            raise ValueError("pairs must be a non-empty list.")
        pairs: list[PairSpec] = []
        for index, pair_entry in enumerate(pair_entries):
            if not isinstance(pair_entry, Mapping):
                raise ValueError(f"pairs[{index}] must be an object.")
            _reject_unknown(pair_entry, {"pair_id", "image_member", "mask_member"}, f"pairs[{index}]")
            pairs.append(
                PairSpec(
                    pair_id=_required_text(pair_entry, "pair_id"),
                    image_member=_required_text(pair_entry, "image_member"),
                    mask_member=_required_text(pair_entry, "mask_member"),
                )
            )
        shape = contract.get("expected_shape")
        if not isinstance(shape, list):
            raise ValueError("expected_shape must be a list.")
        attributes_expected = contract.get("attributes_expected")
        if not isinstance(attributes_expected, bool):
            raise ValueError("attributes_expected must be a boolean.")
        config = cls(
            case_id=_required_text(payload, "case_id"),
            record_id=int(source["record_id"]),
            doi=_required_text(source, "doi"),
            dataset_version=_required_text(source, "dataset_version"),
            license=_required_text(source, "license"),
            source_description=_required_text(source, "source_description"),
            paper_doi=_required_text(literature, "paper_doi"),
            paper_reported_four_k_pixel_size_pm=float(
                literature["paper_reported_four_k_pixel_size_pm"]
            ),
            calibration_binding_status=_required_text(
                literature, "calibration_binding_status"
            ),
            image_archive=image_archive,
            mask_archive=mask_archive,
            pairs=tuple(pairs),
            image_dataset_name=_required_text(contract, "image_dataset_name"),
            mask_dataset_name=_required_text(contract, "mask_dataset_name"),
            expected_shape=tuple(int(value) for value in shape),
            image_dtype=_required_text(contract, "image_dtype"),
            mask_dtype=_required_text(contract, "mask_dtype"),
            image_mean_abs_tolerance=float(contract["image_mean_abs_tolerance"]),
            image_std_abs_tolerance=float(contract["image_std_abs_tolerance"]),
            attributes_expected=attributes_expected,
        )
        config.validate()
        return config

    def validate(self) -> None:
        if not re.fullmatch(r"[a-z0-9_]+", self.case_id):
            raise ValueError("case_id must use lowercase letters, digits, and underscores.")
        if len(self.expected_shape) != 3 or any(value <= 0 for value in self.expected_shape):
            raise ValueError("expected_shape must contain three positive integers.")
        if self.image_mean_abs_tolerance <= 0 or self.image_std_abs_tolerance <= 0:
            raise ValueError("image standardization tolerances must be positive.")
        if self.attributes_expected:
            raise ValueError("this audit supports only the pinned no-attribute HDF5 contract.")
        pair_ids = [pair.pair_id for pair in self.pairs]
        image_members = [pair.image_member for pair in self.pairs]
        mask_members = [pair.mask_member for pair in self.pairs]
        for label, values in (
            ("pair_id", pair_ids),
            ("image_member", image_members),
            ("mask_member", mask_members),
        ):
            if len(set(values)) != len(values):
                raise ValueError(f"{label} values must be unique.")
        for pair in self.pairs:
            _validate_member_name(pair.image_member)
            _validate_member_name(pair.mask_member)
        if set(image_members) != set(self.image_archive.expected_members):
            raise ValueError("source-image pair members do not equal image archive expected_members.")
        if set(mask_members) != set(self.mask_archive.expected_members):
            raise ValueError("mask pair members do not equal mask archive expected_members.")


def load_config(path: str | Path) -> SourceImageMaskPairingConfig:
    payload = json.loads(Path(path).read_text(encoding="utf-8"))
    if not isinstance(payload, dict):
        raise ValueError("case config must contain a JSON object.")
    return SourceImageMaskPairingConfig.from_mapping(payload)


def validate_public_config(config: SourceImageMaskPairingConfig) -> None:
    expected_image_members = tuple(f"{prefix}_TEM_images.h5" for prefix in PUBLIC_PREFIXES)
    expected_mask_members = tuple(
        f"{prefix}_segmented_images.h5" for prefix in PUBLIC_PREFIXES
    )
    expected = {
        "case_id": PUBLIC_CASE_ID,
        "record_id": 14927582,
        "doi": PUBLIC_DOI,
        "dataset_version": PUBLIC_DATASET_VERSION,
        "license": PUBLIC_LICENSE,
        "paper_doi": "10.1021/acsnano.4c09312",
        "paper_reported_four_k_pixel_size_pm": 86.0,
        "calibration_binding_status": "paper_context_not_bound_to_individual_public_hdf5_members",
        "image_dataset_name": "images",
        "mask_dataset_name": "labels",
        "expected_shape": (5, 4096, 4096),
        "image_dtype": "float64",
        "mask_dtype": "float64",
        "image_mean_abs_tolerance": 1e-10,
        "image_std_abs_tolerance": 1e-12,
        "attributes_expected": False,
    }
    for field, value in expected.items():
        actual = getattr(config, field)
        if actual != value:
            raise ValueError(f"public config mismatch for {field}: {actual!r} != {value!r}")
    _validate_public_archive(
        config.image_archive,
        expected_name=PUBLIC_IMAGE_ARCHIVE_NAME,
        expected_md5=PUBLIC_IMAGE_ARCHIVE_MD5,
        expected_sha256=PUBLIC_IMAGE_ARCHIVE_SHA256,
        expected_members=expected_image_members,
        expected_url="https://zenodo.org/records/14927582/files/TEM_images.zip?download=1",
    )
    _validate_public_archive(
        config.mask_archive,
        expected_name=PUBLIC_MASK_ARCHIVE_NAME,
        expected_md5=PUBLIC_MASK_ARCHIVE_MD5,
        expected_sha256=PUBLIC_MASK_ARCHIVE_SHA256,
        expected_members=expected_mask_members,
        expected_url="https://zenodo.org/records/14927582/files/Segmented_images.zip?download=1",
    )
    expected_pairs = tuple(
        PairSpec(
            pair_id=prefix.lower(),
            image_member=f"{prefix}_TEM_images.h5",
            mask_member=f"{prefix}_segmented_images.h5",
        )
        for prefix in PUBLIC_PREFIXES
    )
    if config.pairs != expected_pairs:
        raise ValueError("public source-image/mask pair map does not match the audited contract.")


